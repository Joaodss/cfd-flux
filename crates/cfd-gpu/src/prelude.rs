//! The WGSL constants shared with the CPU reference, generated from the Rust definitions so that
//! no lattice constant or flag bit is ever typed twice. The kernels (`shaders/*.wgsl`) are
//! appended to this prelude when the shader module is created.

use std::fmt::Write as _;

use cfd_core::domain::{flags, LINKS, OPPOSITE};
use cfd_lbm::lattice::{W5, W9};

/// Shader sources: `common` follows the prelude in every module.
pub const COMMON_WGSL: &str = include_str!("../shaders/common.wgsl");
pub const LBM_WGSL: &str = include_str!("../shaders/lbm.wgsl");
pub const REDUCE_WGSL: &str = include_str!("../shaders/reduce.wgsl");

/// `f32` as a WGSL literal. Rust prints the shortest decimal that round-trips, so the value on the
/// GPU is bit-identical to the CPU constant.
fn float(v: f32) -> String {
    let s = format!("{v:?}");
    if s.contains(['.', 'e']) {
        s
    } else {
        format!("{s}.0")
    }
}

fn array<T: Copy>(name: &str, ty: &str, values: &[T], fmt: impl Fn(T) -> String) -> String {
    let items: Vec<String> = values.iter().map(|&v| fmt(v)).collect();
    format!(
        "const {name} = array<{ty}, {}>({});\n",
        values.len(),
        items.join(", ")
    )
}

/// The generated WGSL constants.
pub fn prelude() -> String {
    let mut s = String::from("// Generated by cfd-gpu/src/prelude.rs from cfd-core and cfd-lbm.\n");
    s += &array("LINK_X", "i32", &LINKS.map(|c| c[0]), |v| format!("{v}"));
    s += &array("LINK_Y", "i32", &LINKS.map(|c| c[1]), |v| format!("{v}"));
    s += &array("OPPOSITE", "u32", &OPPOSITE, |v| format!("{v}u"));
    s += &array("W9", "f32", &W9, float);
    s += &array("W5", "f32", &W5, float);
    let consts: [(&str, u16); 14] = [
        ("FLOW_MASK", flags::FLOW_MASK),
        ("FLUID", flags::FLUID),
        ("BOUNCE_BACK", flags::BOUNCE_BACK),
        ("PRESSURE", flags::PRESSURE),
        ("ZERO_GRADIENT", flags::ZERO_GRADIENT),
        ("THERMAL_SHIFT", flags::THERMAL_SHIFT),
        ("THERMAL_MASK", flags::THERMAL_MASK),
        ("ADIABATIC", flags::ADIABATIC),
        ("FIXED_TEMPERATURE", flags::FIXED_TEMPERATURE),
        ("HEAT_FLUX", flags::HEAT_FLUX),
        ("THERMAL_ZERO_GRADIENT", flags::THERMAL_ZERO_GRADIENT),
        ("INWARD_SHIFT", flags::INWARD_SHIFT),
        ("INWARD_MASK", flags::INWARD_MASK),
        ("LINK_SHIFT", flags::LINK_SHIFT),
    ];
    for (name, v) in consts {
        let _ = writeln!(s, "const {name}: u32 = {v}u;");
    }
    s
}

/// The complete source of one shader module: prelude + common types + kernel.
pub fn source(kernel: &str) -> String {
    format!("{}\n{COMMON_WGSL}\n{kernel}", prelude())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn floats_round_trip() {
        for v in W9.into_iter().chain(W5) {
            assert_eq!(float(v).parse::<f32>().unwrap(), v);
        }
        assert_eq!(float(1.0), "1.0");
    }

    #[test]
    fn prelude_has_every_constant() {
        let p = prelude();
        assert!(p.contains("const LINK_X = array<i32, 9>(0, 1, 0, -1, 0, 1, -1, -1, 1);"));
        assert!(p.contains("const OPPOSITE = array<u32, 9>(0u, 3u, 4u, 1u, 2u, 7u, 8u, 5u, 6u);"));
        assert!(p.contains("const LINK_SHIFT: u32 = 8u;"));
    }
}
