//! The comparison report: `README.md` (renders on GitHub), difference maps (PNG), time-series
//! plots (SVG) and a machine-readable `compare.json`, in the style of the validation report.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};
use serde::Serialize;

use super::{CaseComparison, Comparison, Mode};
use crate::{fmt_num, Metric};

/// How the comparison was run.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ReportInfo {
    /// The command line, e.g. `cfd-cli compare scenes/channel.json --steps 1000`.
    pub command: String,
    pub generator: String,
    pub commit: Option<String>,
    pub cpu: String,
    pub threads: usize,
    pub collision: String,
    pub seconds: f64,
    /// Relative path from the report directory to `docs/`, for links (`None`: plain text).
    #[serde(skip)]
    pub docs: Option<String>,
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn status(passed: Option<bool>) -> &'static str {
    match passed {
        Some(true) => "✅ pass",
        Some(false) => "❌ **fail**",
        None => "info",
    }
}

fn sci(v: f64) -> String {
    if v == 0.0 {
        "0".into()
    } else {
        format!("{v:.2e}")
    }
}

fn opt_sci(v: Option<f64>) -> String {
    v.map_or("—".into(), sci)
}

/// One-line verdict of a backend, e.g. `✅ bit-identical` or `❌ 3.1e-4`.
pub fn verdict(c: &Comparison, mode: Mode) -> String {
    let mark = if c.passed { "✅" } else { "❌" };
    if let Some(f) = &c.failure {
        return format!("{mark} {}", cell(f));
    }
    match (c.identical, mode) {
        (true, _) => format!("{mark} bit-identical"),
        (false, Mode::Fields) => format!("{mark} max diff {}", sci(c.max_metric())),
        (false, Mode::Statistics) => {
            let worst = c.checks.iter().filter_map(|m| m.error).fold(0.0, f64::max);
            format!("{mark} statistics within {} (fields differ)", sci(worst))
        }
    }
}

fn link(info: &ReportInfo, text: &str, path: &str) -> String {
    match &info.docs {
        Some(d) => format!("[{text}]({d}/{path})"),
        None => format!("{text} (`docs/{path}`)"),
    }
}

/// Writes the report into `dir`, replacing the images of a previous report. With several
/// cases, image names are prefixed with the case id.
pub fn write(dir: &Path, info: &ReportInfo, cases: &[CaseComparison]) -> Result<()> {
    std::fs::create_dir_all(dir).with_context(|| format!("cannot create {}", dir.display()))?;
    for entry in std::fs::read_dir(dir)?.flatten() {
        let p = entry.path();
        if p.extension().is_some_and(|e| e == "svg" || e == "png") {
            std::fs::remove_file(&p)?;
        }
    }
    let multi = cases.len() > 1;
    let mut md = String::new();
    let _ = writeln!(md, "# Engine comparison\n");
    let _ = writeln!(
        md,
        "Generated by `{}` ({}, commit {}). Each backend runs the same domain from the same initial \
         state and is compared with the first one, the reference. Method and tolerances: {}; parity \
         metric shared with the parity tests (`cfd_verify::parity`).\n",
        cell(&info.command),
        info.generator,
        info.commit.as_deref().unwrap_or("unknown"),
        link(
            info,
            "04 §7",
            "04-numerical-methods.md#7-validation"
        ),
    );
    let _ = writeln!(md, "| CPU | Threads | Collision | Total time | Result |");
    let _ = writeln!(md, "|-----|---------|-----------|------------|--------|");
    let passed = cases.iter().filter(|c| c.passed()).count();
    let _ = writeln!(
        md,
        "| {} | {} | {} | {:.0} s | {passed}/{} {} |\n",
        cell(&info.cpu),
        info.threads,
        info.collision,
        info.seconds,
        cases.len(),
        if multi { "cases pass" } else { "pass" }
    );

    if multi {
        let labels: Vec<&str> = cases
            .first()
            .map(|c| c.runs.iter().skip(1).map(|r| r.label.as_str()).collect())
            .unwrap_or_default();
        let reference = cases
            .first()
            .and_then(|c| c.runs.first())
            .map_or("—", |r| r.label.as_str());
        let _ = writeln!(md, "## Summary (reference: {reference})\n");
        let _ = writeln!(
            md,
            "| Case | Grid | Steps | Mode | {} |",
            labels.join(" | ")
        );
        let _ = writeln!(
            md,
            "|------|------|-------|------|{}",
            "---|".repeat(labels.len())
        );
        for c in cases {
            let cols: Vec<String> = c
                .comparisons
                .iter()
                .map(|x| verdict(x, c.plan.mode))
                .collect();
            let _ = writeln!(
                md,
                "| [{}](#{}) | {}×{} | {} | {} | {} |",
                c.title,
                c.id,
                c.width,
                c.height,
                c.plan.steps,
                mode_name(c.plan.mode),
                cols.join(" | ")
            );
        }
        md.push('\n');
    }

    for c in cases {
        let prefix = if multi {
            format!("{}-", c.id)
        } else {
            String::new()
        };
        case_section(&mut md, c, multi, &prefix);
        for p in &c.plots {
            let file = format!("{prefix}{}", p.file);
            std::fs::write(dir.join(&file), p.to_svg())?;
        }
        let maps = c.comparisons.iter().flat_map(|x| &x.maps);
        for s in c.snapshots.iter().chain(maps) {
            let file = format!("{prefix}{}", s.file);
            std::fs::write(dir.join(&file), s.image.encode_png()?)?;
        }
    }
    notes(&mut md, info);
    std::fs::write(dir.join("README.md"), md)?;

    #[derive(Serialize)]
    struct Json<'a> {
        run: &'a ReportInfo,
        cases: &'a [CaseComparison],
    }
    std::fs::write(
        dir.join("compare.json"),
        serde_json::to_string_pretty(&Json { run: info, cases })? + "\n",
    )?;
    Ok(())
}

fn mode_name(m: Mode) -> &'static str {
    match m {
        Mode::Fields => "fields",
        Mode::Statistics => "statistics",
    }
}

fn metric_table(md: &mut String, metrics: &[Metric]) {
    let _ = writeln!(md, "| Check | Value | Reference | Error | Limit | Result |");
    let _ = writeln!(md, "|-------|-------|-----------|-------|-------|--------|");
    for m in metrics {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} |",
            cell(&m.name),
            fmt_num(m.value),
            cell(&m.reference),
            m.error.map(sci).unwrap_or_default(),
            m.limit.map(sci).unwrap_or_default(),
            status(m.passed())
        );
    }
    md.push('\n');
}

fn case_section(md: &mut String, c: &CaseComparison, multi: bool, prefix: &str) {
    let h = if multi { "###" } else { "##" };
    let reference = c.runs.first().map_or("—", |r| r.label.as_str());
    if multi {
        let _ = writeln!(
            md,
            "<a id=\"{}\"></a>\n## {} — {}\n",
            c.id,
            c.title,
            status(Some(c.passed()))
        );
    } else {
        let _ = writeln!(md, "## {} — {}\n", c.title, status(Some(c.passed())));
    }
    if !c.description.is_empty() {
        let _ = writeln!(md, "{}\n", c.description);
    }
    let p = &c.plan;
    let _ = writeln!(
        md,
        "Grid {}×{} ({} fluid cells{}), {} steps (t = {} s, dt = {} s), {} mode, field tolerance {}{}.\n",
        c.width,
        c.height,
        c.fluid_cells,
        if c.thermal { ", thermal" } else { "" },
        p.steps,
        fmt_num(p.steps as f64 * c.dt),
        fmt_num(c.dt),
        mode_name(p.mode),
        sci(p.tolerance),
        if p.mode == Mode::Statistics {
            format!(
                ", statistics from t = {} s with tolerance {}",
                fmt_num(p.stats_from as f64 * c.dt),
                sci(p.stats_tolerance)
            )
        } else {
            String::new()
        }
    );

    let _ = writeln!(md, "{h} Backends\n");
    let _ = writeln!(md, "| Backend | Device | Steps | Time | MLUPS | Result |");
    let _ = writeln!(md, "|---------|--------|-------|------|-------|--------|");
    for (k, r) in c.runs.iter().enumerate() {
        let result = if k == 0 {
            match &r.failure {
                None => "reference".to_string(),
                Some(f) => format!("❌ {}", cell(f)),
            }
        } else {
            c.comparisons
                .get(k - 1)
                .map_or_else(String::new, |x| verdict(x, p.mode))
        };
        let _ = writeln!(
            md,
            "| {} | {} | {} | {:.2} s | {:.0} | {result} |",
            r.label,
            cell(&r.description),
            r.steps,
            r.seconds,
            r.mlups
        );
    }
    md.push('\n');

    for x in &c.comparisons {
        let _ = writeln!(md, "{h} {} vs {reference}\n", x.backend);
        if let Some(f) = &x.failure {
            let _ = writeln!(md, "> **Not compared:** {}\n", cell(f));
            continue;
        }
        if !x.initial_identical {
            let _ = writeln!(
                md,
                "> **The initial fields differ from the reference's** (they must be bit-identical).\n"
            );
        }
        let _ = writeln!(
            md,
            "**Lattice fields** (pass/fail on the 04 §7 metric{})\n",
            if p.mode == Mode::Statistics {
                " in fields mode; information only here"
            } else {
                ""
            }
        );
        let _ = writeln!(
            md,
            "| Field | Max abs. diff | Rel. L2 | 04 §7 metric | Limit | Bit-identical |"
        );
        let _ = writeln!(
            md,
            "|-------|---------------|---------|--------------|-------|---------------|"
        );
        for f in &x.fields {
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} | {} |",
                f.field,
                sci(f.max_abs),
                opt_sci(f.rel_l2),
                opt_sci(f.metric),
                if p.mode == Mode::Fields {
                    sci(p.tolerance)
                } else {
                    "—".into()
                },
                if f.identical { "yes" } else { "no" }
            );
        }
        md.push('\n');
        if !x.physical.is_empty() {
            let _ = writeln!(md, "**Output fields** (physical units, information)\n");
            let _ = writeln!(
                md,
                "| Field | Unit | Max abs. diff | Rel. L2 | Bit-identical |"
            );
            let _ = writeln!(
                md,
                "|-------|------|---------------|---------|---------------|"
            );
            for f in &x.physical {
                let _ = writeln!(
                    md,
                    "| {} | {} | {} | {} | {} |",
                    f.field,
                    f.unit,
                    sci(f.max_abs),
                    opt_sci(f.rel_l2),
                    if f.identical { "yes" } else { "no" }
                );
            }
            md.push('\n');
        }
        let _ = writeln!(md, "**Checks**\n");
        metric_table(md, &x.checks);
        for s in &x.maps {
            let _ = writeln!(
                md,
                "![{}]({prefix}{})\n*{}*\n",
                s.caption, s.file, s.caption
            );
        }
    }

    // Diagnostics side by side.
    let _ = writeln!(md, "{h} Diagnostics after the last step\n");
    let labels: Vec<&str> = c.runs.iter().map(|r| r.label.as_str()).collect();
    let _ = writeln!(md, "| Quantity | {} |", labels.join(" | "));
    let _ = writeln!(md, "|----------|{}", "---|".repeat(labels.len()));
    type Get = fn(&super::DiagSummary) -> Option<f64>;
    let rows: [(&str, Get); 4] = [
        ("mass Σρ (lattice)", |d| Some(d.mass)),
        ("kinetic energy (lattice)", |d| Some(d.kinetic_energy)),
        ("max \\|u\\| (m/s)", |d| Some(d.max_velocity)),
        ("thermal energy Σθ (lattice)", |d| d.thermal_energy),
    ];
    for (name, get) in rows {
        let vals: Vec<Option<f64>> = c
            .runs
            .iter()
            .map(|r| r.diagnostics.as_ref().and_then(get))
            .collect();
        if vals.iter().all(Option::is_none) {
            continue;
        }
        let cols: Vec<String> = vals
            .iter()
            .map(|v| v.map_or("—".into(), |v| format!("{v:.9e}")))
            .collect();
        let _ = writeln!(md, "| {name} | {} |", cols.join(" | "));
    }
    md.push('\n');

    // Forces after the last step.
    if c.elements.iter().any(|e| e.loaded) {
        let _ = writeln!(md, "{h} Forces after the last step (N/m)\n");
        let _ = writeln!(md, "| Element | Backend | Fx | Fy |");
        let _ = writeln!(md, "|---------|---------|----|----|");
        for (k, el) in c.elements.iter().enumerate().filter(|(_, e)| e.loaded) {
            for r in &c.runs {
                if let Some(f) = r.forces.get(k) {
                    let _ = writeln!(
                        md,
                        "| {} | {} | {:.6e} | {:.6e} |",
                        cell(&el.name),
                        r.label,
                        f[0],
                        f[1]
                    );
                }
            }
        }
        md.push('\n');
    }

    // Force statistics.
    let has_stats = c.runs.iter().any(|r| !r.statistics.is_empty());
    if has_stats && c.elements.iter().any(|e| e.loaded) {
        let _ = writeln!(
            md,
            "{h} Force statistics from t = {} s{}\n",
            fmt_num(p.stats_from as f64 * c.dt),
            if p.mode == Mode::Fields {
                " (information)"
            } else {
                ""
            }
        );
        let _ = writeln!(
            md,
            "Coefficients C = 2F/(ρ₀U²L) and St = fL/U with L = {} m, U = {} m/s.\n",
            fmt_num(p.ref_length),
            fmt_num(p.ref_velocity)
        );
        let _ = writeln!(
            md,
            "| Element | Backend | Fx mean | Fx min | Fx max | Fy mean | Fy min | Fy max | C_x mean | C_x max | C_y max | f (Hz) | St |"
        );
        let _ = writeln!(
            md,
            "|---------|---------|---------|--------|--------|---------|--------|--------|----------|---------|---------|--------|----|"
        );
        let k = c.coefficient_scale;
        for (i, el) in c.elements.iter().enumerate().filter(|(_, e)| e.loaded) {
            for r in &c.runs {
                let Some(s) = r.statistics.get(i) else {
                    continue;
                };
                let _ = writeln!(
                    md,
                    "| {} | {} | {:.5e} | {:.5e} | {:.5e} | {:.5e} | {:.5e} | {:.5e} | {} | {} | {} | {} | {} |",
                    cell(&el.name),
                    r.label,
                    s.x.mean,
                    s.x.min,
                    s.x.max,
                    s.y.mean,
                    s.y.min,
                    s.y.max,
                    fmt_num(s.x.mean * k),
                    fmt_num(s.x.max * k),
                    fmt_num(s.y.max * k),
                    s.frequency.map_or("—".into(), |f| format!("{f:.5}")),
                    s.frequency
                        .map_or("—".into(), |f| format!("{:.5}", f * p.ref_length / p.ref_velocity)),
                );
            }
        }
        md.push('\n');
    }

    if !c.snapshots.is_empty() || !c.plots.is_empty() {
        let _ = writeln!(md, "{h} Reference fields and time series\n");
    }
    for s in &c.snapshots {
        let _ = writeln!(
            md,
            "![{}]({prefix}{})\n*{}*\n",
            s.caption, s.file, s.caption
        );
    }
    for pl in &c.plots {
        let _ = writeln!(md, "![{}]({prefix}{})\n", pl.title, pl.file);
    }
}

fn notes(md: &mut String, info: &ReportInfo) {
    let _ = writeln!(md, "## Notes\n");
    let _ = writeln!(
        md,
        "- **Fields mode:** pass when the 04 §7 metric of every lattice field is within the \
         tolerance — ρ in absolute terms, ux and uy relative to the largest velocity component of \
         the reference, θ relative to its maximum — and the kinetic energy, max |u| (1e-5, \
         relative) and the force on each loaded element (1e-4 of the largest force) agree, as in \
         the parity tests. Mass is conserved by construction in a closed domain and must agree to \
         1e-7; with inlets or outlets Σρ follows the flow, and its relative difference (the mean \
         density difference) is held to the field tolerance. *Bit-identical* means every value \
         has the same bits; CUDA (compiled without fused multiply-adds) is expected to be \
         bit-identical to the CPU, wgpu to differ by round-off (its driver contracts \
         multiply-adds)."
    );
    let _ = writeln!(
        md,
        "- **Statistics mode:** in chaotic or unsteady-periodic flows (e.g. the von Kármán street \
         behind the Re = 100 cylinder) round-off differences grow until the instantaneous fields \
         are unrelated, while the statistics are unchanged. The verdict then uses the time \
         series instead, over the statistics window: the oscillation frequency (relative), the \
         mean, minimum and maximum of each force component (relative to the largest force) and \
         the mean kinetic energy (relative). The mass of a closed domain must still agree to \
         1e-7. The field tables are shown for information."
    );
    let _ = writeln!(
        md,
        "- **MLUPS** here is the throughput while comparing, with a synchronisation at every \
         sample of the time series; {} gives the clean numbers.",
        link(info, "`cfd-cli bench`", "benchmarks.md")
    );
}
